-- Run AFTER the existing supabase_setup.sql in Supabase SQL Editor.
-- Safe to run more than once.

alter table public.attendees
    add column if not exists degree text,
    add column if not exists semester text,
    add column if not exists graduation_year text,
    add column if not exists fee_amount integer,
    add column if not exists payment_status text not null default 'LEGACY_APPROVED',
    add column if not exists payment_method text,
    add column if not exists payment_order_id uuid;

-- Existing attendees were already approved by the previous system. Preserve them.
update public.attendees
set payment_status = 'LEGACY_APPROVED'
where payment_status is null or payment_status = '';

create unique index if not exists attendees_payment_order_id_uidx
    on public.attendees(payment_order_id)
    where payment_order_id is not null;

create index if not exists attendees_roll_degree_idx
    on public.attendees (lower(trim(roll_number)), coalesce(degree, '')); 

create table if not exists public.payment_orders (
    id uuid primary key default gen_random_uuid(),
    full_name text not null,
    degree text not null check (degree in ('BS', 'MS', 'PhD', 'Alumni')),
    semester text,
    graduation_year text,
    roll_number text,
    department text,
    email text,
    phone text not null,
    amount integer not null check (amount in (4000, 6000, 10000)),
    payment_method text not null default 'JazzCash',
    transaction_reference text not null,
    sender_phone text,
    payment_date date,
    status text not null default 'SUBMITTED'
        check (status in ('SUBMITTED', 'PAID', 'REJECTED', 'DUPLICATE', 'MANUAL_REVIEW')),
    review_note text,
    attendee_id text,
    submitted_at timestamptz not null default now(),
    verified_at timestamptz,
    verified_by text
);

create unique index if not exists payment_orders_transaction_reference_uidx
    on public.payment_orders (lower(trim(transaction_reference)));

create index if not exists payment_orders_status_submitted_idx
    on public.payment_orders(status, submitted_at desc);

create table if not exists public.payment_events (
    id bigint generated by default as identity primary key,
    payment_order_id uuid references public.payment_orders(id) on delete set null,
    event_type text not null,
    event_details jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default now()
);

alter table public.payment_orders enable row level security;
alter table public.payment_events enable row level security;
-- No anon/public policies. Streamlit uses the service-role key from Secrets.

create or replace function public.approve_igeo_payment(
    p_payment_id uuid,
    p_token_hash text,
    p_verified_by text default 'IGEO FEST Admin'
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
    p public.payment_orders%rowtype;
    v_attendee_id text;
begin
    select * into p
    from public.payment_orders
    where id = p_payment_id
    for update;

    if not found then
        return jsonb_build_object('status', 'NOT_FOUND');
    end if;

    if p.status = 'PAID' and p.attendee_id is not null then
        return jsonb_build_object('status', 'ALREADY_PAID', 'attendee_id', p.attendee_id);
    end if;

    if p.status <> 'SUBMITTED' then
        return jsonb_build_object('status', 'NOT_PENDING', 'current_status', p.status);
    end if;

    if p_token_hash is null or length(p_token_hash) < 32 then
        return jsonb_build_object('status', 'INVALID_TOKEN');
    end if;

    -- Serialize approvals for the same degree + roll number to prevent duplicates.
    if p.degree <> 'Alumni' and nullif(trim(p.roll_number), '') is not null then
        perform pg_advisory_xact_lock(hashtext(lower(trim(p.roll_number))), hashtext(p.degree));
        if exists (
            select 1 from public.attendees a
            where lower(trim(a.roll_number)) = lower(trim(p.roll_number))
              and coalesce(a.degree, '') = p.degree
              and a.revoked = false
        ) then
            return jsonb_build_object('status', 'DUPLICATE', 'message', 'This student roll number is already registered for this degree.');
        end if;
    end if;

    v_attendee_id := 'IGEO-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 10));

    insert into public.attendees (
        attendee_id, full_name, roll_number, category, department, email, phone,
        registration_status, ticket_status, token_hash, revoked,
        degree, semester, graduation_year, fee_amount, payment_status,
        payment_method, payment_order_id, created_at
    ) values (
        v_attendee_id, p.full_name, nullif(p.roll_number, ''),
        case when p.degree = 'Alumni' then 'Alumni' else p.degree || ' Student' end,
        nullif(p.department, ''), nullif(p.email, ''), p.phone,
        'APPROVED', 'NOT_USED', p_token_hash, false,
        p.degree, nullif(p.semester, ''), nullif(p.graduation_year, ''), p.amount,
        'PAID', 'JazzCash', p.id, now()
    );

    update public.payment_orders
    set status = 'PAID', attendee_id = v_attendee_id,
        verified_at = now(), verified_by = p_verified_by
    where id = p.id;

    insert into public.payment_events(payment_order_id, event_type, event_details)
    values (p.id, 'ADMIN_VERIFIED_PAID', jsonb_build_object(
        'attendee_id', v_attendee_id, 'amount', p.amount,
        'transaction_reference', p.transaction_reference, 'verified_by', p_verified_by
    ));

    return jsonb_build_object('status', 'SUCCESS', 'attendee_id', v_attendee_id);
exception
    when unique_violation then
        return jsonb_build_object('status', 'DUPLICATE', 'message', 'This roll number or transaction reference is already registered.');
end;
$$;

create or replace function public.reject_igeo_payment(
    p_payment_id uuid,
    p_reason text,
    p_reviewed_by text default 'IGEO FEST Admin'
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
    p public.payment_orders%rowtype;
begin
    select * into p from public.payment_orders where id = p_payment_id for update;
    if not found then return jsonb_build_object('status', 'NOT_FOUND'); end if;
    if p.status <> 'SUBMITTED' then
        return jsonb_build_object('status', 'NOT_PENDING', 'current_status', p.status);
    end if;
    update public.payment_orders
    set status = 'REJECTED', review_note = left(coalesce(p_reason, 'Not verified'), 500),
        verified_at = now(), verified_by = p_reviewed_by
    where id = p.id;
    insert into public.payment_events(payment_order_id, event_type, event_details)
    values (p.id, 'ADMIN_REJECTED', jsonb_build_object('reason', left(coalesce(p_reason, ''), 500), 'reviewed_by', p_reviewed_by));
    return jsonb_build_object('status', 'REJECTED');
end;
$$;

revoke all on function public.approve_igeo_payment(uuid, text, text) from public;
revoke all on function public.reject_igeo_payment(uuid, text, text) from public;
grant execute on function public.approve_igeo_payment(uuid, text, text) to service_role;
grant execute on function public.reject_igeo_payment(uuid, text, text) to service_role;
