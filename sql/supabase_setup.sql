-- IGEO FEST Cloud Database Setup (run once in Supabase SQL Editor)
create table if not exists public.attendees (
    attendee_id text primary key,
    full_name text not null,
    roll_number text,
    category text,
    department text,
    email text,
    phone text,
    registration_status text not null default 'APPROVED',
    ticket_status text not null default 'NOT_ISSUED',
    token_hash text unique,
    checked_in_at timestamptz,
    revoked boolean not null default false,
    created_at timestamptz not null default now()
);

create table if not exists public.scan_logs (
    id bigint generated by default as identity primary key,
    attendee_id text,
    result text not null,
    scanned_at timestamptz not null default now(),
    details text
);

alter table public.attendees enable row level security;
alter table public.scan_logs enable row level security;

-- Do not add anon/public policies. The app uses the Supabase service-role
-- key stored only in Streamlit Secrets, never in GitHub source code.

create or replace function public.confirm_igeo_entry(p_token_hash text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
    a public.attendees%rowtype;
    v_now timestamptz := now();
begin
    select * into a
    from public.attendees
    where token_hash = p_token_hash
    for update;

    if not found then
        insert into public.scan_logs(attendee_id,result,details)
        values (null,'INVALID','Token not found');
        return jsonb_build_object('status','INVALID');
    end if;

    if a.revoked then
        insert into public.scan_logs(attendee_id,result,details)
        values (a.attendee_id,'REVOKED','Ticket revoked');
        return jsonb_build_object('status','REVOKED');
    end if;

    if a.registration_status <> 'APPROVED' then
        insert into public.scan_logs(attendee_id,result,details)
        values (a.attendee_id,'NOT_APPROVED','Registration not approved');
        return jsonb_build_object('status','NOT_APPROVED');
    end if;

    if a.checked_in_at is not null then
        insert into public.scan_logs(attendee_id,result,details)
        values (a.attendee_id,'DUPLICATE','Ticket already checked in');
        return jsonb_build_object('status','DUPLICATE','checked_in_at',a.checked_in_at);
    end if;

    update public.attendees
    set checked_in_at = v_now, ticket_status = 'USED'
    where attendee_id = a.attendee_id;

    insert into public.scan_logs(attendee_id,result,details)
    values (a.attendee_id,'VALID','Entry confirmed');

    return jsonb_build_object('status','VALID','attendee_id',a.attendee_id,'checked_in_at',v_now);
end;
$$;

revoke all on function public.confirm_igeo_entry(text) from public;
grant execute on function public.confirm_igeo_entry(text) to service_role;
